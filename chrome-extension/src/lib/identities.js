// Writes the file Burp's Identities -> Import reads (IdentityTransfer, format 1).
// Every identity shares the generated script and differs only in credentials.

/** The Burp extension's default; kept in step with Identity.java. */
export const DEFAULT_STRIP = 'Authorization, Cookie, X-CSRF-Token, X-XSRF-Token, X-Auth-Token, X-Api-Key';

/**
 * @param script      generated Groovy source
 * @param plan        analysis.plan, for the session settings
 * @param identities  [{ name, credentials: { [param]: value } }]
 */
export function identityExport(script, plan, identities) {
  const strip = DEFAULT_STRIP.split(',').map((s) => s.trim());
  for (const h of plan.result.headers) {
    if (!strip.some((s) => s.toLowerCase() === h.name.toLowerCase())) strip.push(h.name);
  }
  const declared = new Set(plan.params.map((p) => p.name));
  return {
    format: 1,
    note: 'Contains credentials in clear text. Treat as sensitive.',
    identities: identities.map((identity) => {
      const credentials = {};
      for (const [name, value] of Object.entries(identity.credentials || {})) {
        // Base has a default in the script, so an empty one is left for it to fill.
        if (name === 'base' && !value) continue;
        if (declared.has(name) || name === 'base') credentials[name] = value ?? '';
      }
      return {
        name: identity.name || 'Recorded identity',
        enabled: true,
        notes: `Generated by the Auth Check Recorder from a login recorded against ${plan.baseOrigin || 'the target'}.`,
        credentials,
        authScript: script,
        staticHeaders: '',
        stripHeaders: strip.join(', '),
        tokenHeaderName: 'Authorization',
        refreshIntervalSeconds: 0,
        sessionInvalidRegex: '',
        reauthOnDenied: true,
        sessionCheckUrl: plan.sessionCheckUrl || '',
        sessionValidRegex: '',
      };
    }),
  };
}
